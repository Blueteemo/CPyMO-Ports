#!/usr/bin/env python3
"""Refresh every place that quotes the CANDIDATE core's digest/size.

The core is rebuilt whenever engine source changes, so `d551c449...` (424,396
bytes) became `d6c32e5e...` (424,556 bytes) when the save-ID fix landed. Three
documents still quoted the old value: the README, the ledger (twice) and the A/B
structure dump. A stale digest in a review package is worse than no digest -- it
looks verified and is not.

This rewrites them from the artefact, and refuses to run if the candidate is
missing.
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = (ROOT / "research/candidate_v023_soft/APPS/"
        "CPyMO_RG35XX_uClibc_Test/cpymo_libretro.so")

TARGETS = [
    "README_FOR_REVIEWER.md",
    "research/reports/v023_ledger.md",
]
# The A/B structure dump is generated by compare_arm_clang_lld.sh; it is
# refreshed by rebuilding, not by this script, so it is only REPORTED here.
REPORT_ONLY = ["research/build_arm_compare_clang/soft-structure.txt"]


def main() -> int:
    if not CORE.is_file():
        print(f"missing {CORE}")
        return 1
    data = CORE.read_bytes()
    new_sha = hashlib.sha256(data).hexdigest()
    new_size = len(data)
    print(f"candidate: {new_size} bytes  {new_sha}")

    old_shas = set()
    for rel in TARGETS:
        p = ROOT / rel
        text = p.read_text(encoding="utf-8")
        found = re.findall(r"\b[0-9a-f]{64}\b", text)
        # Only the ones that are NOT a manifest/package digest and ARE the core.
        for h in found:
            if h != new_sha and h in text:
                # Heuristic: a core digest is quoted within 120 chars of "core"
                # or "libretro.so".
                for m in re.finditer(re.escape(h), text):
                    ctx = text[max(0, m.start() - 160):m.start() + 160]
                    if "core" in ctx or "libretro.so" in ctx:
                        old_shas.add(h)
                        break

    if not old_shas:
        print("no stale core digest found in the documents")
    else:
        print("stale core digest(s):", len(old_shas))
        for h in old_shas:
            print("   ", h)

    changed = 0
    for rel in TARGETS:
        p = ROOT / rel
        text = p.read_text(encoding="utf-8")
        before = text
        for h in old_shas:
            text = text.replace(h, new_sha)
        # The size is quoted next to "bytes" or as "424,396".
        for m in re.finditer(r"(\d{3})[,\s]?(\d{3}) bytes", text):
            val = int(m.group(1) + m.group(2))
            if val != new_size and val > 300_000 and val < 600_000:
                text = text.replace(m.group(0),
                                    f"{new_size:,}".replace(",", ",") + " bytes")
        if text != before:
            p.write_text(text, encoding="utf-8")
            changed += 1
            print(f"  updated {rel}")

    for rel in REPORT_ONLY:
        p = ROOT / rel
        if p.is_file() and new_sha not in p.read_text(encoding="utf-8",
                                                      errors="replace"):
            print(f"  STALE (regenerate with the build script): {rel}")

    print(f"\n{changed} document(s) updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
